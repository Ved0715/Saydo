import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { idFromPath } from '../core/capability';
import { scanProject, type ScanResult } from './scan';

export const OUT_DIR = '.saydo';
export const REGISTRY_FILE = 'registry.ts';

/** Default-export id for a capability file, from its path. */
export function fileIdFor(projectDir: string, file: string, capabilityDirs: string[]): string {
  for (const dir of capabilityDirs) {
    const root = path.join(projectDir, dir);
    if (file.startsWith(root + path.sep)) return idFromPath(path.relative(root, file));
  }
  // Colocated app/**/capabilities.ts: id from URL segments (groups and params dropped).
  const rel = path.relative(projectDir, path.dirname(file)).split(path.sep);
  const segments = rel
    .slice(rel[0] === 'src' ? 2 : 1)
    .filter((s) => s && !/^\(.*\)$/.test(s) && !s.startsWith('[') && !s.startsWith('@') && !s.startsWith('_'));
  return segments.join('.') || 'app';
}

function importPath(fromDir: string, file: string): string {
  let rel = path.relative(fromDir, file).split(path.sep).join('/');
  rel = rel.replace(/\.(tsx|ts|jsx|js|mjs)$/, '');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

export function devSecret(outDir: string): string {
  fs.mkdirSync(outDir, { recursive: true });
  const file = path.join(outDir, 'dev-secret');
  try {
    const existing = fs.readFileSync(file, 'utf8').trim();
    if (existing.length >= 32) return existing;
  } catch {
    // first run
  }
  const secret = crypto.randomBytes(32).toString('hex');
  fs.writeFileSync(file, secret, { mode: 0o600 });
  return secret;
}

/**
 * Write `.saydo/registry.ts`: static imports of every capability module and
 * colocated nav.ts, so the route handler gets the whole surface with zero
 * manual wiring. Only writes when the content changes, to avoid HMR loops.
 */
export function generateRegistry(projectDir: string, options: { dev?: boolean; capabilityDirs?: string[] } = {}): ScanResult {
  const scan = scanProject(projectDir, options);
  const outDir = path.join(projectDir, OUT_DIR);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, '.gitignore'), '*\n');

  const lines = [
    '// Generated by saydo from your app/ tree and capabilities/. Do not edit.',
    "import 'server-only';",
    "import { collectCapabilities, withFileId, type RouteRecord } from 'saydo-js';",
  ];
  const capabilityDirs = options.capabilityDirs ?? ['capabilities', 'src/capabilities'];
  scan.capabilityFiles.forEach((file, i) => lines.push(`import * as cap${i} from '${importPath(outDir, file)}';`));
  const configFile = ['saydo.config.ts', 'saydo.config.mts', 'saydo.config.js', 'saydo.config.mjs']
    .map((name) => path.join(projectDir, name))
    .find((file) => fs.existsSync(file));
  if (configFile) lines.push(`import config from '${importPath(outDir, configFile)}';`);
  const navImports = scan.routes.filter((r) => r.nav);
  navImports.forEach((route, i) => lines.push(`import nav${i} from '${importPath(outDir, route.nav!)}';`));
  lines.push('', 'export const routes: RouteRecord[] = [');
  for (const route of scan.routes) {
    const index = navImports.indexOf(route);
    lines.push(`  { pattern: ${JSON.stringify(route.pattern)}${index >= 0 ? `, nav: nav${index}` : ''} },`);
  }
  lines.push('];', '');
  const modules = scan.capabilityFiles.map(
    (file, i) => `withFileId(cap${i}, ${JSON.stringify(fileIdFor(projectDir, file, capabilityDirs))})`,
  );
  lines.push(`export const capabilities = collectCapabilities(${modules.join(', ')});`);
  lines.push(configFile ? 'export { config };' : 'export const config = {};');
  lines.push(`export const devSecret: string | undefined = ${options.dev ? JSON.stringify(devSecret(outDir)) : 'undefined'};`);
  lines.push('');

  const content = lines.join('\n');
  const file = path.join(outDir, REGISTRY_FILE);
  let previous = '';
  try {
    previous = fs.readFileSync(file, 'utf8');
  } catch {
    // first run
  }
  if (previous !== content) fs.writeFileSync(file, content);
  return scan;
}
