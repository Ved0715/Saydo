/// <reference path="./virtual.d.ts" />
import fs from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';
import { devSecret, fileIdFor, OUT_DIR, scanProject } from '../next/index';
import { toNodeHandler } from './node';

export interface SaydoViteOptions {
  /** Route the client talks to. Default '/api/saydo'. */
  endpoint?: string;
  /** Folders scanned for capability modules. Default: capabilities/, src/capabilities/. */
  capabilityDirs?: string[];
  /**
   * In-page browser agents (WebMCP). By default the dev server sends
   * `Permissions-Policy: tools=()` so no script on the page can register browser-agent tools;
   * `agents: true` sends `tools=(self)`. Pass the same option to `serveStatic` in production.
   */
  agents?: boolean;
}

const REGISTRY_ID = 'saydo/registry';
const HANDLER_ID = 'virtual:saydo/handler';
const RESOLVED_REGISTRY = '\0saydo:registry';
const RESOLVED_HANDLER = '\0saydo:handler';
const EMPTY = '\0saydo:empty';

function firstExisting(root: string, names: string[]): string | undefined {
  return names.map((n) => path.join(root, n)).find((file) => fs.existsSync(file));
}

const rootRelative = (root: string, file: string) => `/${path.relative(root, file).split(path.sep).join('/')}`;

/**
 * saydo for Vite + React apps. Discovers capabilities/, saydo.routes.ts and
 * saydo.config.ts, serves the assistant endpoint in dev, and exposes
 * `virtual:saydo/handler` for your production server entry.
 */
export function saydo(options: SaydoViteOptions = {}): Plugin {
  const endpoint = options.endpoint ?? '/api/saydo';
  const capabilityDirs = options.capabilityDirs ?? ['capabilities', 'src/capabilities'];
  let root = process.cwd();
  let serve = true;

  function registryCode(): string {
    const { capabilityFiles } = scanProject(root, { capabilityDirs });
    const routesFile = firstExisting(root, ['saydo.routes.ts', 'saydo.routes.tsx', 'src/saydo.routes.ts', 'saydo.routes.js']);
    const configFile = firstExisting(root, ['saydo.config.ts', 'saydo.config.mts', 'saydo.config.js', 'saydo.config.mjs']);
    const lines = [
      '// Generated by the saydo Vite plugin.',
      "import { collectCapabilities, withFileId } from 'saydo';",
      ...capabilityFiles.map((file, i) => `import * as cap${i} from ${JSON.stringify(rootRelative(root, file))};`),
    ];
    if (routesFile) lines.push(`import routes from ${JSON.stringify(rootRelative(root, routesFile))};`);
    if (configFile) lines.push(`import config from ${JSON.stringify(rootRelative(root, configFile))};`);
    const modules = capabilityFiles.map((file, i) => `withFileId(cap${i}, ${JSON.stringify(fileIdFor(root, file, capabilityDirs))})`);
    lines.push(
      routesFile ? 'export { routes };' : 'export const routes = [];',
      `export const capabilities = collectCapabilities(${modules.join(', ')});`,
      configFile ? 'export { config };' : 'export const config = {};',
      `export const devSecret = ${serve ? JSON.stringify(devSecret(path.join(root, OUT_DIR))) : 'undefined'};`,
    );
    return lines.join('\n');
  }

  return {
    name: 'saydo',
    enforce: 'pre',

    config() {
      // saydo ships TypeScript sources; let Vite process them for the server build too.
      return { ssr: { noExternal: ['saydo'] } };
    },

    configResolved(config) {
      root = config.root;
      serve = config.command === 'serve';
    },

    resolveId(id, _importer, resolveOptions) {
      const server = this.environment?.config.consumer === 'server' || resolveOptions?.ssr === true;
      if (id === REGISTRY_ID || id === HANDLER_ID) {
        if (!server) {
          this.error(`${id} is server-only (fix: import it from your server entry, never from browser code).`);
        }
        return id === REGISTRY_ID ? RESOLVED_REGISTRY : RESOLVED_HANDLER;
      }
      if (id === 'server-only') {
        if (server) return EMPTY;
        this.error('A server-only module was imported from browser code (fix: move the import to a capability, entity or server file).');
      }
      return null;
    },

    load(id) {
      if (id === RESOLVED_REGISTRY) return registryCode();
      if (id === RESOLVED_HANDLER) {
        return [
          `import * as registry from ${JSON.stringify(REGISTRY_ID)};`,
          "import { createHandler } from 'saydo/handler';",
          'export const POST = createHandler(registry);',
        ].join('\n');
      }
      if (id === EMPTY) return 'export {};';
      return null;
    },

    configureServer(server) {
      const watched = [...capabilityDirs.map((d) => path.join(root, d)), path.join(root, 'saydo.routes'), path.join(root, 'saydo.config')];
      const onFileSetChange = (file: string) => {
        if (!watched.some((prefix) => file.startsWith(prefix))) return;
        for (const environment of Object.values(server.environments)) {
          const node = environment.moduleGraph.getModuleById(RESOLVED_REGISTRY);
          if (node) environment.moduleGraph.invalidateModule(node);
        }
      };
      server.watcher.on('add', onFileSetChange);
      server.watcher.on('unlink', onFileSetChange);

      server.middlewares.use((_req, res, next) => {
        res.setHeader('Permissions-Policy', options.agents ? 'tools=(self)' : 'tools=()');
        next();
      });
      server.middlewares.use(async (req, res, next) => {
        if (req.method !== 'POST' || req.url?.split('?')[0] !== endpoint) return next();
        try {
          const handler = (await server.ssrLoadModule(HANDLER_ID)) as { POST: (request: Request) => Promise<Response> };
          await toNodeHandler(handler.POST)(req, res);
        } catch (error) {
          if (error instanceof Error) server.ssrFixStacktrace(error);
          next(error);
        }
      });
    },
  };
}

export { toNodeHandler, serveStatic } from './node';
